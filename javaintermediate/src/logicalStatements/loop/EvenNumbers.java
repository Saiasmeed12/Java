package logicalStatements.loop;

public class EvenNumbers {

	public static void main(String[] args) {
	
		System.out.print("The Even Number Are:- ");
		for(int i=1;i<=100;i++) {
			if(i%2 ==0) {
				System.out.print(i+" ");
			}
			
		}
		

	}
	

}

